"""Reproduce the simulated-data experiment of docs/ml/DESIGN.md section 9, end to end.

    python scripts/sim_experiment.py [--per-scenario 120] [--out data/sim]

1. simulate a labelled dataset from the data-engine plan (seed 7)
2. train the radar (healthy training traces only) and the classifier (parameter region A only)
3. evaluate both on held-out simulated data (the protocol of section 5)
4. score the real QNX 8.0 bug-zoo traces in fixtures/real with the same frozen models
   (a development set since 2026-11-15: it was used to find sim-to-real gaps; see section 9)
and writes everything to docs/ml/results_sim.md. Deterministic: same code, same numbers.
"""

from __future__ import annotations

import argparse
import shutil
import sys
import time
from collections import Counter
from pathlib import Path

from tracelens.analyze import analyze_file
from tracelens.config import load_config
from tracelens.ml import dataset, evaluate, model as M, train
from tracelens.ml.features import vector, windows
from tracelens.sim.dataset import generate

ROOT = Path(__file__).resolve().parents[1]
REAL = ROOT / "fixtures" / "real"


def real_rows(radar: dict, clf: dict) -> list[str]:
    cfg = load_config(REAL / "tracelens.toml")
    out = ["| Real QNX 8.0 trace | Rules (HIGH+) | Radar (persistent unusual threads) | Classifier (victim thread: cause) |",
           "|---|---|---|---|"]
    for p in sorted(REAL.glob("*.txt.gz")):
        a = analyze_file(p, cfg)
        m = a.model
        rows = [(m.label(k), f) for k, _, _, f in windows(m)]
        per = M.persistence(radar, rows)
        flagged = sorted(((u / n, t, u, n) for t, (u, n) in per.items() if M.thread_flagged(radar, u, n)), reverse=True)
        votes: dict[str, Counter] = {}
        for t, f in rows:
            pr = M.ensemble_proba(clf, vector(f))
            votes.setdefault(t, Counter())[max(pr, key=pr.get)] += 1
        causes = sorted(((c.most_common(1)[0][1] / sum(c.values()), t, c.most_common(1)[0][0]) for t, c in votes.items()
                         if c.most_common(1)[0][0] != dataset.HEALTHY and sum(c.values()) >= 3
                         and c.most_common(1)[0][1] > 0.5 * sum(c.values())), reverse=True)
        rules = sorted({f.kind for f in a.findings if f.severity in ("high", "critical")})
        out.append(f"| `{p.name.replace('.txt.gz', '')}` | {', '.join(rules) or 'none'} | "
                   f"{', '.join(f'{t} ({u}/{n})' for _, t, u, n in flagged[:3]) or 'quiet'} | "
                   f"{', '.join(f'{t}: {k}' for _, t, k in causes[:2]) or 'healthy'} |")
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--per-scenario", type=int, default=120)
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--out", default=str(ROOT / "data" / "sim"))
    ap.add_argument("--report", default=str(ROOT / "docs" / "ml" / "results_sim.md"))
    args = ap.parse_args()
    out = Path(args.out)
    if out.exists():
        shutil.rmtree(out)
    t0 = time.time()
    plan = dataset.make_plan(args.per_scenario, args.seed)
    rows = [r for r in generate(plan, out, str(ROOT / "bugzoo/gen/tlgen.toml"), plan_seed=args.seed, log=lambda s: None)
            if r.get("status") == "ok"]
    t_sim = time.time() - t0
    feats = dataset.read_jsonl(out / "features.jsonl")
    radar = train.train_radar(feats)
    clf = train.train_classifier(feats)
    M.save(radar, out / "radar.json")
    M.save(clf, out / "classifier.json")
    by = Counter((r["scenario"], bool(r["triggered"])) for r in rows)
    md = ["# TraceLens ML on simulated QNX traces: results", "",
          f"Generated by `python scripts/sim_experiment.py --per-scenario {args.per_scenario} --seed {args.seed}` "
          f"({len(rows)} simulated traces, {len(feats):,} thread windows, {t_sim:.0f} s to simulate and analyze). "
          "Models are trained once and frozen before any number below is computed. Method: "
          "[DESIGN.md](DESIGN.md) sections 5 and 9.", "",
          "## Data: did each planted problem show up?", "",
          "| Scenario | Label | Traces | Planted problem showed up |", "|---|---|---|---|"]
    for name, sc in dataset.SCENARIOS.items():
        n = by[(name, True)] + by[(name, False)]
        md.append(f"| `{name}` | {sc.label} | {n} | {by[(name, True)]}/{n} |")
    md += ["", "`lock_contention` misses are mild variants (2-3 workers, short work) that the contention rule grades "
           "MEDIUM, below the HIGH gate: graded, not missed.", "",
           evaluate.markdown(evaluate.evaluate_radar(feats, radar), evaluate.evaluate_classifier(feats, clf)).strip(), "",
           "Classifier labels are per thread: only the planted victim's windows carry the bug's label "
           "(`dataset.window_label`). `ipc_deadlock` has a fixed period, so it has no region-B test windows.", "",
           "## Sim-to-real: the same frozen models on real QNX 8.0 captures", "",
           "Neither model has seen a real trace. These traces were used to find the simulator's gaps "
           "(DESIGN.md section 9), so this is a development set, not a clean test.", ""]
    md += real_rows(radar, clf)
    md += ["", f"Radar: {radar['note']}; window threshold {radar['threshold']:.2f}; a thread is reported when more than "
               f"{radar['min_frac']:.0%} of its windows (and at least {radar['min_windows']}) are unusual.",
           f"Classifier: {clf['note']}.", ""]
    Path(args.report).write_text("\n".join(md), encoding="utf-8", newline="\n")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    sys.exit(main())
